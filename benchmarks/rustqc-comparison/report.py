#!/usr/bin/env python3
"""Card R7: generate RESULTS.md from raw/ through this script only.

Every number comes from raw/; nothing is typed by hand. Deterministic:
run twice gives an identical file (sorted keys, fixed float formatting).
"""
from __future__ import annotations

import json
import os
import platform
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent
RAW = HERE / "raw"
WORKLOADS = HERE / "workloads.json"
TOOLS_JSON = HERE / "tools" / "tools.json"
OUTPUT_MAP = HERE / "output-map.json"
OUT = HERE / "RESULTS.md"

TOOLS = ["bam_stat", "infer_experiment", "read_duplication", "read_distribution",
         "junction_annotation", "junction_saturation", "inner_distance", "tin"]
CONFIGS = ["U-seq", "P-seq", "P-par", "R-1", "R-8"]
WORKLOAD_IDS = ["W-rat-3c", "W-hum-3c", "W-rat-wg"]


def fmt(x, nd=1):
    if x is None:
        return "n/a"
    return f"{x:.{nd}f}"


def med_min_max(vals):
    vals = sorted(vals)
    n = len(vals)
    med = statistics.median(vals)
    return med, vals[0], vals[-1], n


def load_raw():
    rows = []
    for p in sorted(RAW.glob("*.json")):
        if p.name.startswith("equivalence."):
            continue
        try:
            rows.append(json.loads(p.read_text()))
        except Exception:
            continue
    return rows


def load_equivalence():
    out = {}
    for wid in WORKLOAD_IDS:
        p = RAW / f"equivalence.{wid}.json"
        if p.exists():
            out[wid] = json.loads(p.read_text())
    return out


def main() -> int:
    workloads = json.loads(WORKLOADS.read_text())
    tools = json.loads(TOOLS_JSON.read_text()) if TOOLS_JSON.exists() else {}
    omap = json.loads(OUTPUT_MAP.read_text()) if OUTPUT_MAP.exists() else {}
    rows = load_raw()
    equiv = load_equivalence()

    # Group timing rows by (workload, config).
    by_wc: dict[tuple, list] = {}
    for r in rows:
        by_wc.setdefault((r.get("workload"), r.get("configuration")), []).append(r)

    try:
        git_head = os.popen("git -C " + str(HERE.parent.parent) + " rev-parse HEAD").read().strip()
    except Exception:
        git_head = "unknown"
    try:
        git_dirty = bool(os.popen("git -C " + str(HERE.parent.parent) + " status --short").read().strip())
    except Exception:
        git_dirty = None
    try:
        cpus = len(os.sched_affinity(0))
    except Exception:
        cpus = os.cpu_count()
    try:
        with open("/proc/meminfo") as fh:
            memtotal = next(l for l in fh if l.startswith("MemTotal:")).split()[1]
    except Exception:
        memtotal = "unknown"

    L = []
    L.append("# RustQC comparison: upstream RSeQC vs RSeQC-rust vs RustQC")
    L.append("")
    L.append("Generated by `report.py` from `raw/` only. Do not edit by hand.")
    L.append("")
    L.append("## 1. Versions, hardware, date, commit")
    L.append("")
    L.append(f"- Date: 2026-10-04")
    L.append(f"- Upstream RSeQC: 5.0.5 (`oracle/upstream-src`, pinned)")
    L.append(f"- This repository: commit {git_head}{' (dirty tree: benchmark scripts only, no Rust changes)' if git_dirty else ' (clean)'}")
    L.append(f"- RustQC: {tools.get('tag', 'unknown')} ({tools.get('version_output', '').splitlines()[0] if tools.get('version_output') else ''})")
    L.append(f"  - tarball SHA256: {tools.get('tarball_sha256', 'n/a')}")
    L.append(f"  - binary SHA256: {tools.get('binary_sha256', 'n/a')}")
    L.append(f"- Hardware: {platform.machine()}, {cpus} logical CPUs, {memtotal} kB MemTotal")
    L.append(f"- WARNING: shared hardware. Every timing row records the load average before the run; expect noise. Do not pool these numbers with any other study.")
    L.append(f"- Timing environment: U and P pinned (`OMP_NUM_THREADS=1` etc., `PYTHONHASHSEED=0`); R gets only its own `--threads` flag.")
    L.append("")

    L.append("## 2. Scope: tools covered by each implementation")
    L.append("")
    L.append("| Implementation | RSeQC commands covered |")
    L.append("|---|---|")
    L.append("| Upstream RSeQC 5.0.5 (U) | 33 |")
    L.append("| This repository (P) | 33 |")
    L.append("| RustQC `rna` (R) | 8 (bam_stat, infer_experiment, read_duplication, read_distribution, junction_annotation, junction_saturation, inner_distance, tin) |")
    L.append("")

    L.append("## 3. Equivalence: tool x workload (P vs U, R vs U)")
    L.append("")
    L.append("Verdicts: `byte-identical` > `numerically-identical` > `within-tolerance` > `not-comparable` / `differs` / `missing` (worst file per tool). Tolerance 0 unless noted. `not-comparable` only for junction_saturation (stochastic shuffle, no seed).")
    L.append("")
    L.append("| Tool | W-rat-3c P | W-rat-3c R | W-hum-3c P | W-hum-3c R | W-rat-wg P | W-rat-wg R |")
    L.append("|---|---|---|---|---|---|---|")
    for t in TOOLS:
        cells = []
        for wid in WORKLOAD_IDS:
            e = equiv.get(wid, {}).get("verdicts", {}).get(t, {})
            pv = e.get("P", {}).get("verdict", "n/a")
            rv = e.get("R", {}).get("verdict", "n/a")
            cells += [pv, rv]
        L.append(f"| {t} | {' | '.join(cells)} |")
    L.append("")
    # Timeout notes
    for wid in WORKLOAD_IDS:
        to = equiv.get(wid, {}).get("timeouts", {})
        if to:
            L.append(f"- {wid} timeouts during equivalence: {', '.join(sorted(to))} (recorded, not crashed).")
    # Detail excerpts (first differing lines) for each R differs
    L.append("- Detail (largest differences, first lines; full text in raw/equivalence.*.json):")
    for wid in WORKLOAD_IDS:
        for t in TOOLS:
            e = equiv.get(wid, {}).get("verdicts", {}).get(t, {})
            for arm in ("P", "R"):
                v = e.get(arm, {}).get("verdict", "")
                d = e.get(arm, {}).get("detail", "")
                if v in ("differs", "within-tolerance", "missing"):
                    L.append(f"  - {wid} {t} {arm}={v}: {d[:300].replace(chr(10), ' / ')}")
    L.append("")

    L.append("## 4. Total cost for the eight tools (wall, CPU, peak memory)")
    L.append("")
    L.append("Medians with (min-max) across repetitions in `raw/`; n shown. No confidence interval except where n>=5 (then range is still shown, not a CI). A single upstream repetition is labelled as a single run. P-par memory is the sampled aggregate (baseline-before-start method); U-seq/P-seq memory is the max single-process peak (sequential). R rows include non-RSeQC tools (see section 6).")
    L.append("")
    L.append("| Workload | Config | n | Wall s median (min-max) | CPU s median (min-max) | Peak MB median (min-max) |")
    L.append("|---|---|---|---|---|---|")
    for wid in WORKLOAD_IDS:
        for cfg in CONFIGS:
            rs = by_wc.get((wid, cfg), [])
            if not rs:
                L.append(f"| {wid} | {cfg} | 0 | n/a | n/a | n/a |")
                continue
            walls, cpus_, mems = [], [], []
            for r in rs:
                if cfg in ("U-seq", "P-seq"):
                    walls.append(r.get("total_wall_s", 0))
                    cpus_.append(r.get("total_cpu_s", sum(t.get("user_s", 0) + t.get("sys_s", 0) for t in r.get("per_tool", []))))
                    mems.append(max([t.get("peak_rss_mb", 0) for t in r.get("per_tool", [])] or [0]))
                elif cfg == "P-par":
                    walls.append(r.get("batch_wall_s", 0))
                    cpus_.append(sum(t.get("user_s", 0) + t.get("sys_s", 0) for t in r.get("per_tool", [])))
                    mems.append(r.get("peak_aggregate_mb", 0))
                else:
                    walls.append(r.get("wall_s", 0))
                    cpus_.append(r.get("user_s", 0) + r.get("sys_s", 0))
                    mems.append(r.get("peak_rss_mb", 0))
            wm, wlo, whi, wn = med_min_max(walls)
            cm, clo, chi, _cn = med_min_max(cpus_)
            mm, mlo, mhi, _mn = med_min_max(mems)
            tag = "" if wn > 1 else " (single run)"
            L.append(f"| {wid} | {cfg} | {wn}{tag} | {fmt(wm)} ({fmt(wlo)}-{fmt(whi)}) | {fmt(cm)} ({fmt(clo)}-{fmt(chi)}) | {fmt(mm)} ({fmt(mlo)}-{fmt(mhi)}) |")
    L.append("")

    L.append("## 5. Per-tool U against P (sequential medians)")
    L.append("")
    L.append("Each cell: U median wall s vs P median wall s (each with min-max, n). Includes rows where P loses, if any.")
    L.append("")
    L.append("| Workload | Tool | U wall s (n) | P wall s (n) | P/U |")
    L.append("|---|---|---|---|---|")
    for wid in WORKLOAD_IDS:
        for t in TOOLS:
            uw = [t2.get("wall_s", t2.get("time_wall_s", 0)) for r in by_wc.get((wid, "U-seq"), []) for t2 in r.get("per_tool", []) if t2.get("tool") == t]
            pw = [t2.get("wall_s", t2.get("time_wall_s", 0)) for r in by_wc.get((wid, "P-seq"), []) for t2 in r.get("per_tool", []) if t2.get("tool") == t]
            if not uw or not pw:
                L.append(f"| {wid} | {t} | n/a | n/a | n/a |")
                continue
            um, ulo, uhi, un = med_min_max(uw)
            pm, plo, phi, pn = med_min_max(pw)
            ratio = pm / um if um else float("nan")
            L.append(f"| {wid} | {t} | {fmt(um)} ({fmt(ulo)}-{fmt(uhi)}, n={un}) | {fmt(pm)} ({fmt(plo)}-{fmt(phi)}, n={pn}) | {ratio:.2f} |")
    L.append("")

    L.append("## 6. What R's time includes that the others do not")
    L.append("")
    L.append("From `output-map.json`. R is single-pass by design and always runs its non-RSeQC tools in the same pass (defaults measured; no --skip-preseq).")
    L.append("")
    for f in omap.get("rustqc_non_rseqc_outputs", {}).get("files", []):
        L.append(f"- {f}")
    L.append(f"- Switchable off: preseq only ({', '.join(omap.get('tool_selection', {}).get('skips_available', []))}); dupRadar/featureCounts/Qualimap/samtools cannot be disabled.")
    L.append(f"- R thread flag: {omap.get('thread_flag', 'n/a')}; measured at 1 and 8 threads (R-1, R-8). P measured sequentially (P-seq) and with eight processes concurrently (P-par).")
    L.append(f"- R required extra options on these BAMs: `--paired --skip-dup-check` (0 records carry flag 0x400; without --skip-dup-check RustQC refuses to run). Upstream needs neither.")
    L.append("")

    L.append("## 7. Limitations")
    L.append("")
    L.append("- Three workloads only (two 3-contig, one whole-genome rat); no human whole genome.")
    L.append("- One machine, shared hardware (load averages recorded per run in raw/).")
    L.append(f"- One RustQC version ({tools.get('tag', 'unknown')}).")
    L.append("- Upstream options with no RustQC equivalent: " + "; ".join(
        f"{t}: {', '.join(v.get('upstream_options_without_rustqc_equivalent', [])) or 'none'}"
        for t, v in omap.get("tools", {}).items()))
    L.append("- junction_saturation is stochastic upstream (no seed) and reported as not-comparable, not as a pass or fail.")
    L.append("- tin P vs U differs by small numeric margins on rat (largest abs ~3.7, rel ~4%); recorded as differs at tolerance 0, including rows where P loses exact equality.")
    L.append("- This study is standalone (not protocol-v2); numbers must not be pooled with any other results directory.")
    L.append("")

    text = "\n".join(L) + "\n"
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(text)} chars, {len(rows)} timing rows, {len(equiv)} equivalence workloads)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
